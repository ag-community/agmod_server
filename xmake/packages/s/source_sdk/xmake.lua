package("source_sdk")
    set_kind("library", { headeronly = true })
    set_description("Half-Life 1 Source SDK headers")
    set_urls("https://github.com/tmp64/hl1_source_sdk/archive/11f26656677c881c7c630d03957900e7701da62e.tar.gz")
    add_versions("11f2665", "822d0f6fdd112fabac3257a67d2e23d4d9ba3a655e13fd248fa4f775341f2f0b")

    on_load(function (package)
        package:add("includedirs", "include/common")
        package:add("includedirs", "include/public")
        package:add("includedirs", "include/public/tier0")
    end)

    on_install(function (package)
        local inc = package:installdir("include")
        os.mkdir(inc)
        os.cp("common", inc)
        os.cp("public", inc)
        os.mkdir(package:installdir("share/source_sdk"))
        os.cp("LICENSE", package:installdir("share/source_sdk"))
    end)
package_end()
