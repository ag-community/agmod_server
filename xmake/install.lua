target("server")
    -- Install the mod layout instead of xmake's default lib layout.
    on_install(function (target)
        local root = target:installdir()
        local dlls = path.join(root, "dlls")
        os.mkdir(dlls)
        os.cp(target:targetfile(), dlls)

        local symbolfile = target:symbolfile()
        if symbolfile and os.isfile(symbolfile) then
            os.cp(symbolfile, dlls)
        end

        local gamedir = path.join(os.projectdir(), "gamedir")
        for _, file in ipairs(os.files(path.join(gamedir, "**"))) do
            local dest = path.join(root, path.relative(file, gamedir))
            os.mkdir(path.directory(dest))
            os.cp(file, dest)
        end

        local projectdir = os.projectdir()
        local gamedata_dir = path.join(root, "addons/amxmodx/data/gamedata/common.games/custom")

        -- Generated by just amxx-offsets.
        local amxx_dir = path.join(projectdir, "build/amxx-offsets")
        if os.isdir(amxx_dir) then
            os.mkdir(gamedata_dir)
            for _, file in ipairs(os.files(path.join(amxx_dir, "*.txt"))) do
                os.cp(file, gamedata_dir)
            end
        end
        local amxx_json = os.files(path.join(projectdir, "build/ag-amxx-offsets-*.json"))
        if #amxx_json > 0 then
            os.mkdir(gamedata_dir)
            for _, file in ipairs(amxx_json) do
                os.cp(file, gamedata_dir)
            end
        end

        -- Generated by just hamdata.
        local hamdata = path.join(projectdir, "build/hamdata.ini")
        if os.isfile(hamdata) then
            local configs_dir = path.join(root, "addons/amxmodx/configs")
            os.mkdir(configs_dir)
            os.cp(hamdata, configs_dir)
        end
    end)
target_end()
